"use strict";

const models = {
  diffwave: {
    name: "DiffWave",
    clean: n => `DiffWave/DiffWave_audio${n}.wav`,
    ours: n => `Warden/DiffWave_wmd${n}.wav`,
    baselines: [
      { name: "Groot", path: n => `Groot/groot_wmd${n}.wav` },
      { name: "RIWF", path: n => `RIWF/riwf_wmd${n}.wav` },
    ],
  },
  hifigan: {
    name: "HiFi-GAN",
    clean: n => `HiFiGAN/HifiGAN_audio${n}.wav`,
    ours: n => `Warden/HifiGAN_wmd${n}.wav`,
    baselines: [{ name: "HFGW", path: n => `HFGw/hfgw_wmd${n}.wav` }],
  },
};
let state;
function readState() {
  const params = new URLSearchParams(location.search);
  const model = Object.hasOwn(models, params.get("model")) ? params.get("model") : "diffwave";
  const value = params.get("sample");
  return { model, sample: /^[1-5]$/.test(value || "") ? Number(value) : 1 };
}
function element(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text) node.textContent = text;
  return node;
}
function card({ name, path, kind, index, description }) {
  const article = element("article", `audio-card ${kind === "ours" ? "ours-card" : kind === "clean" ? "reference-card" : ""}`);
  const top = element("div", "card-top");
  top.append(element("span", "method-index", index), element("span", "method-type", kind === "clean" ? "Unwatermarked" : kind === "ours" ? "Model-integrated" : "Baseline"));
  const title = element("div", "card-title-row");
  title.append(element("h3", "", name));
  if (kind === "ours") title.append(element("span", "featured-tag", "OUR METHOD"));
  article.append(top, title);
  if (description) article.append(element("p", "", description));
  const audio = document.createElement("audio");
  audio.controls = true;
  audio.preload = "metadata";
  audio.src = path;
  audio.setAttribute("aria-label", `${name}, ${models[state.model].name}, sample ${state.sample}`);
  audio.addEventListener("play", () => {
    document.querySelectorAll("audio").forEach(other => { if (other !== audio) other.pause(); });
  });
  const error = element("p", "audio-error", "Audio could not be loaded. Try downloading the WAV file.");
  error.hidden = true;
  audio.addEventListener("error", () => { error.hidden = false; });
  const download = element("a", "download-link", "Download WAV");
  download.href = path;
  download.download = path.split("/").pop();
  download.setAttribute("aria-label", `Download ${name}, ${models[state.model].name}, sample ${state.sample}`);
  article.append(audio, error, download);
  return article;
}
function render() {
  document.querySelectorAll("audio").forEach(audio => audio.pause());
  const model = models[state.model];
  const number = String(state.sample).padStart(2, "0");
  document.querySelectorAll("[data-model]").forEach(button => button.setAttribute("aria-pressed", String(button.dataset.model === state.model)));
  document.querySelectorAll("[data-sample]").forEach(button => button.setAttribute("aria-pressed", String(Number(button.dataset.sample) === state.sample)));
  document.querySelector("#selection-label").textContent = `NOW COMPARING ${model.name.toUpperCase()} · EVALUATION SAMPLE ${number}`;
  document.querySelector("#selection-title").textContent = `${model.name} · Sample ${number}`;
  const reference = element("div", "reference-column");
  reference.append(element("h3", "column-heading", "•  START HERE"), card({ name: "Clean speech", path: model.clean(state.sample), kind: "clean", index: "REF", description: `Original unwatermarked speech generated by ${model.name}.` }));
  const outputs = element("div", "outputs-column");
  outputs.append(element("h3", "column-heading", "•  WATERMARKED OUTPUTS"), card({ name: "Warden", path: model.ours(state.sample), kind: "ours", index: "OUR METHOD", description: "Watermark introduced during speech synthesis." }));
  const heading = element("div", "group-heading");
  heading.append(element("span", "", "BASELINE WATERMARKING"), element("span", "", `${model.name} comparison`));
  const grid = element("div", "card-grid");
  model.baselines.forEach((method, i) => grid.append(card({ name: method.name, path: method.path(state.sample), kind: "baseline", index: String(i + 1).padStart(2, "0") })));
  outputs.append(heading, grid);
  document.querySelector("#audio-layout").replaceChildren(reference, outputs);
}
function select(next) {
  state = { ...state, ...next };
  const url = new URL(location.href);
  url.searchParams.set("model", state.model);
  url.searchParams.set("sample", state.sample);
  history.replaceState(null, "", url);
  render();
}
document.querySelectorAll("[data-model]").forEach(button => button.addEventListener("click", () => select({ model: button.dataset.model })));
document.querySelectorAll("[data-sample]").forEach(button => button.addEventListener("click", () => select({ sample: Number(button.dataset.sample) })));
window.addEventListener("popstate", () => { state = readState(); render(); });
state = readState();
render();
